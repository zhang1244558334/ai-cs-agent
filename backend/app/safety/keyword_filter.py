BLOCKED_WORDS = {
    # 诱导私下交易/泄露隐私（主动引导用户离开平台）
    "私人微信", "私人电话", "电话号码", "加我微信", "私下联系",
    "加我QQ", "扫码加我",
    # 脏话（≥2 字，单字如"日/靠/操"误伤"日期/可靠"）
    "操你妈", "傻逼", "草泥马", "你妈逼", "废物", "去死", "滚蛋",
    "他妈", "特么", "操蛋", "混蛋", "王八蛋", "狗屎", "放屁",
    "他妈的", "妈的", "我操",
}
REPLACEMENT = "[安全提醒] 请通过平台官方渠道沟通，不要透露个人联系方式。"


def filter_output(text: str) -> str:
    """过滤 AI 输出中的危险词：替换命中词而非整条拦截。

    注意：微信/支付宝/银行卡/QQ/手机号/身份证 是业务必答内容
    （支付方式/物流查询/实名验证），不得过滤。
    只过滤「主动引诱用户离开平台私下联系」的话术和脏话。
    """
    for word in BLOCKED_WORDS:
        if word in text:
            text = text.replace(word, REPLACEMENT)
    return text
